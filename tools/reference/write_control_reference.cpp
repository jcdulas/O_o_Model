// Render Markdown from the same command and parameter catalogues that the reader uses.
#include "oor/model/control/case_control/CommandCatalogue.hpp"
#include "oor/model/parameters/ParameterCatalogue.hpp"

#include <algorithm>
#include <charconv>
#include <cctype>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <stdexcept>
#include <vector>

using namespace oor::model;
namespace fs = std::filesystem;

namespace
{
std::string number(double value)
{
    char buffer[64];
    const auto [end, error] = std::to_chars(buffer, buffer + sizeof(buffer), value);
    if (error != std::errc{})
        throw std::runtime_error("Could not format a catalogue default");
    return {buffer, end};
}

std::string defaultValue(const ParamDefault& value)
{
    switch (value.kind)
    {
    case ParameterKind::Integer: return std::to_string(value.integerValue);
    case ParameterKind::Real: return number(value.realValue);
    case ParameterKind::Complex: return number(value.realValue) + ";" + number(value.imaginaryValue);
    case ParameterKind::Text: return std::string(value.textValue);
    case ParameterKind::Blank: return {};
    }
    throw std::runtime_error("Unknown parameter kind");
}

std::string_view arguments(const CommandDefinition& command)
{
    switch (command.shape)
    {
    case CommandShape::Integer: return ";integer";
    case CommandShape::IntegerOrKeyword: return ";integer-or-word";
    case CommandShape::Real: return ";real";
    case CommandShape::Keyword: return ";word";
    case CommandShape::Text: return ";text";
    case CommandShape::IntegerList: return ";integer[,integer...]";
    case CommandShape::RealList: return ";real[,real...]";
    case CommandShape::Output: return "[;All|None|set-id][;option...]";
    case CommandShape::Flag: return "";
    case CommandShape::SubcaseHeader: return command.subcaseKind == SubcaseKind::AuxiliaryCase ? "" : ";id";
    case CommandShape::SetDefinition: return ";set-id;members...";
    case CommandShape::Parameter: return ";name;value...";
    case CommandShape::BlockHeader: return command.blockKind.empty() ? ";;block-kind" : "";
    }
    throw std::runtime_error("Unknown case command shape");
}

template <class Range>
void words(std::ostream& out, std::string_view label, const Range& values)
{
    if (values.empty()) return;
    out << "\n" << label;
    for (const auto& word : values) out << " `" << word << "`";
    out << "\n";
}

void entry(std::ostream& out, const CommandDefinition& command)
{
    out << "`" << command.name << arguments(command) << "`\n";
    words(out, "Listed keywords", command.keywords);
    words(out, "Variant options", command.variants);
    for (const auto& qualified : command.qualifiedWords)
        words(out, "Qualifiers for `" + qualified.word + "`", qualified.qualifiers);
    if (command.takesLoadSequence) out << "\nUse a comma inside the value field to append a load sequence to the ID.\n";
    if (command.isBlockCommand) out << "\nUsed inside an output block.\n";
    if (!command.blockKind.empty()) out << "\nOpens the `" << command.blockKind << "` block.\n";
}

void entry(std::ostream& out, const ParamInfo& param)
{
    out << "Type `" << paramTypeName(param.type) << "`. ";
    if (param.defaultValue.exists()) out << "Catalogue default `" << defaultValue(param.defaultValue) << "`.\n";
    else out << "The catalogue supplies no fixed default.\n";
    words(out, "Listed values", param.allowedValues());
    if (param.numbered) out << "\nThis base name also accepts a decimal suffix.\n";
}

template <class Range>
void writeIndex(const fs::path& path, std::string_view title, std::string_view introduction, const Range& catalogue)
{
    std::vector<typename Range::value_type> sorted(catalogue.begin(), catalogue.end());
    std::ranges::sort(sorted, {}, &Range::value_type::name);
    std::ofstream out;
    out.exceptions(std::ios::badbit | std::ios::failbit);
    out.open(path, std::ios::binary);
    out << "# " << title << "\n\n" << introduction << "\n\n"
        << "<!-- Generated by tools/reference/write_control_reference.cpp. -->\n";
    char letter = 0;
    for (const auto& item : sorted)
    {
        if (item.name.front() == letter) continue;
        if (letter != 0) out << " · ";
        letter = item.name.front();
        out << "[" << letter << "](#" << static_cast<char>(std::tolower(static_cast<unsigned char>(letter))) << ")";
    }
    out << "\n";
    letter = 0;
    for (const auto& item : sorted)
    {
        if (item.name.front() != letter)
        {
            letter = item.name.front();
            out << "\n## " << letter << "\n";
        }
        out << "\n### " << item.name << "\n\n";
        entry(out, item);
    }
    out.close();
}
} // namespace

int main(int argc, char** argv)
{
    if (argc != 2)
    {
        std::cerr << "Usage: write_control_reference docs/reference\n";
        return 1;
    }
    const fs::path dest = argv[1];
    writeIndex(dest / "case-commands.md", "Case commands A–Z",
               "Look up the neutral command name to find its record shape. Lowercase terms stand for values. "
               "Square brackets mark optional fields and vertical bars separate alternatives. "
               "See [Case Control](case-control.md) for scope and worked examples.",
               CommandCatalogue::instance().definitions());
    writeIndex(dest / "parameter-index.md", "Parameters A–Z",
               "Each entry gives the accepted type and the fixed default when one is declared. "
               "A complex default is written as two fields, real part first. "
               "See [Parameters](parameters.md) for placement and processor families.",
               ParameterCatalogue::instance().entries());
}
